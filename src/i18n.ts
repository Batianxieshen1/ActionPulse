const DICTS: Record<Lang, Record<TKey, string>> = { zh, en };

/* ------------------------------ 语言状态（模块级单例） ------------------------------ */

let currentLang: Lang = "zh";
const listeners = new Set<() => void>();

function subscribe(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/** 由 App 在 settings.language 变化时调用；驱动 useT 的重渲染。 */
export function setLanguage(next: Lang): void {
  if (next === currentLang) return;
  currentLang = next;
  for (const listener of listeners) listener();
}

export function getLanguage(): Lang {
  return currentLang;
}

/** 任意位置可用的翻译（含非 React 代码：语录、hook 里的 toast）。 */
export function tr(key: TKey, params?: Record<string, string | number>): string {
  let text: string = DICTS[currentLang][key];
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

/** 组件内使用：语言切换时自动重渲染。 */
export function useT(): (key: TKey, params?: Record<string, string | number>) => string {
  useSyncExternalStore(subscribe, () => currentLang);
  return useCallback(tr, []);
}
